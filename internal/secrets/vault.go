// Passphrase reads the KEK passphrase from the environment.
//
// From a file if ORBIT_KEK_PASSPHRASE_FILE is set, otherwise from
// ORBIT_KEK_PASSPHRASE. The file form exists because it is what
// `systemd-creds --with-key=host+tpm2` produces: the passphrase is sealed to the
// machine's TPM and appears as a file the unit can read, never as an environment
// variable that `ps`, a crash dump, or `docker inspect` would carry.
//
// FALLS BACK TO THE CA KEY PASSPHRASE. A deployment that already set
// ORBIT_CA_KEY_PASSPHRASE for its on-disk CA key should not have to set a second
// secret to keep working — the two protect the same material for the same
// reason, and demanding a new variable at upgrade time is how an upgrade turns
// into an outage. New deployments should set the KEK one.
func Passphrase() ([]byte, error) {
	for _, v := range []struct{ file, direct string }{
		{"ORBIT_KEK_PASSPHRASE_FILE", "ORBIT_KEK_PASSPHRASE"},
		{"ORBIT_CA_KEY_PASSPHRASE_FILE", "ORBIT_CA_KEY_PASSPHRASE"},
	} {
		if path := os.Getenv(v.file); path != "" {
			b, err := os.ReadFile(path)
			if err != nil {
				return nil, fmt.Errorf("read %s: %w", v.file, err)
			}
			// Trailing newline trimmed: every way of producing this file adds
			// one, and a passphrase that works from `echo -n` and fails from
			// `echo` is a bug report nobody enjoys.
			return bytes.TrimRight(b, "\r\n"), nil
		}
		if s := os.Getenv(v.direct); s != "" {
			return []byte(s), nil
		}
	}
	return nil, ErrNoKEK
}
